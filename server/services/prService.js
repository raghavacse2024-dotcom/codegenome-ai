/**
 * Automated Pull Request Service for CodeGenome AI
 * Interacts with GitHub REST API to create branches, tree objects, commits, and Pull Requests.
 * Validates diffs through safety guardrails and isolated sandbox before proposing changes.
 */

import { validatePrGuardrails } from './prGuardrails.js'
import { validateRefactor } from './refactorValidator.js'

function getCleanToken(customToken) {
  if (customToken && typeof customToken === 'string') {
    const clean = customToken.trim()
    if (clean.length > 5 && !clean.startsWith('optional_') && !clean.startsWith('your_')) return clean
  }
  const token = process.env.GITHUB_TOKEN?.trim()
  if (!token || token.startsWith('optional_') || token.startsWith('your_') || token.length < 10) return null
  return token
}

function githubHeaders(token) {
  return {
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'User-Agent': 'CodeGenome-AI',
    ...(token ? { Authorization: `Bearer ${token}` } : {}),
  }
}

/**
 * Creates a Pull Request on GitHub with guardrails and sandbox validation.
 * If write permissions exist on target repo, pushes branch directly.
 * If write permissions do NOT exist, automatically forks repo, pushes branch to user's fork, and creates cross-fork PR!
 */
export async function createPullRequest({
  owner,
  repository,
  defaultBranch = 'main',
  title,
  branch,
  body,
  files = [],
  patch = '',
  token = null,
  user = null,
  targetPath = null,
  refactoredTarget = null,
  confirmedHighRisk = false,
}) {
  // Normalize files array to ensure content is always present
  const normalizedFiles = files.map((f) => ({
    path: f.path,
    content: f.content !== undefined ? f.content : (f.newContent !== undefined ? f.newContent : ''),
  }))

  // 1. Enforce PR Safety Guardrails
  const guardrailCheck = validatePrGuardrails({
    files: normalizedFiles,
    patch,
    confirmedHighRisk,
  })

  if (!guardrailCheck.passed) {
    return {
      success: false,
      mode: 'blocked',
      error: guardrailCheck.reason,
      violations: guardrailCheck.violations,
      isHighRisk: guardrailCheck.isHighRisk,
      validation: {
        tests: 'skipped',
        lint: 'skipped',
        typecheck: 'skipped',
        build: 'skipped',
        safeToPropose: false,
      },
    }
  }

  // 2. Run Isolated Validation Sandbox
  const validationResult = await validateRefactor({
    files: normalizedFiles,
    targetPath,
    refactoredTarget,
  })

  if (!validationResult.validation.safeToPropose) {
    return {
      success: false,
      mode: 'validation_failed',
      error: `Refactor validation failed at step '${validationResult.failedStep}'. PR proposal blocked.`,
      validation: validationResult.validation,
      failedStep: validationResult.failedStep,
      logs: validationResult.logs,
    }
  }

  const cleanToken = getCleanToken(token)
  const safeBranch = branch || `codegenome/refactor-${Date.now().toString(36)}`
  const prTitle = title || `refactor(architecture): CodeGenome validation-backed refactor`
  const prBody = body || `## CodeGenome AI Automated Refactor\n\n- **Target Repository**: ${owner}/${repository}\n- **Base Branch**: ${defaultBranch}\n- **Automated Branch**: ${safeBranch}\n\n### Validation Pipeline Status\n- Tests: ${validationResult.validation.tests}\n- Lint / Syntax: ${validationResult.validation.lint}\n- Typecheck: ${validationResult.validation.typecheck}\n- Build: ${validationResult.validation.build}\n\n### Summary\nAI-assisted refactoring recommendations informed by AST metrics. This refactor extracts monolithic logic into modular units with unit tests.\n\n---\n*Generated by [CodeGenome AI](https://codegenome.ai)*`

  const cliCommand = `git checkout -b ${safeBranch} && git apply --whitespace=fix patch.diff`
  const userLogin = user?.login || 'arulraghav07'
  let apiUserLogin = userLogin
  let targetBaseBranch = defaultBranch

  // If live GitHub token is present, attempt live push & pull request creation via GitHub REST API
  if (cleanToken && owner.toLowerCase() !== 'demo') {
    try {
      // Get authenticated user info
      const userRes = await fetch('https://api.github.com/user', {
        headers: githubHeaders(cleanToken),
        signal: AbortSignal.timeout(8_000),
      })
      if (!userRes.ok) {
        throw new Error(`Failed to verify user token (${userRes.status})`)
      }
      const userData = await userRes.json()
      apiUserLogin = userData.login

      // Query repository metadata and permissions
      const repoRes = await fetch(`https://api.github.com/repos/${owner}/${repository}`, {
        headers: githubHeaders(cleanToken),
        signal: AbortSignal.timeout(8_000),
      })
      if (!repoRes.ok) {
        throw new Error(`Failed to fetch metadata for ${owner}/${repository} (${repoRes.status})`)
      }
      const repoData = await repoRes.json()
      targetBaseBranch = repoData.default_branch || defaultBranch
      const canPush = Boolean(repoData.permissions?.push || repoData.permissions?.admin)

      let targetOwner = owner
      let isCrossFork = false

      if (!canPush && apiUserLogin) {
        isCrossFork = true
        targetOwner = apiUserLogin

        // Fork repository to user's account
        const forkRes = await fetch(`https://api.github.com/repos/${owner}/${repository}/forks`, {
          method: 'POST',
          headers: githubHeaders(cleanToken),
          signal: AbortSignal.timeout(10_000),
        })
        if (!forkRes.ok && forkRes.status !== 202) {
          throw new Error(`Failed to initiate repository fork (${forkRes.status})`)
        }

        // Poll up to 6 times to ensure fork repository is created and ready
        let forkReady = false
        for (let attempt = 0; attempt < 6; attempt++) {
          await new Promise((r) => setTimeout(r, 2000))
          const checkFork = await fetch(`https://api.github.com/repos/${targetOwner}/${repository}`, {
            headers: githubHeaders(cleanToken),
            signal: AbortSignal.timeout(5_000),
          })
          if (checkFork.ok) {
            forkReady = true
            break
          }
        }

        if (!forkReady) {
          throw new Error(`Fork repository ${targetOwner}/${repository} creation timed out.`)
        }
      }

      // Get reference commit of base branch
      const refRes = await fetch(
        `https://api.github.com/repos/${owner}/${repository}/git/ref/heads/${encodeURIComponent(targetBaseBranch)}`,
        { headers: githubHeaders(cleanToken), signal: AbortSignal.timeout(8_000) }
      )
      if (!refRes.ok) {
        throw new Error(`Failed to get ref commit for base branch ${targetBaseBranch} (${refRes.status})`)
      }
      const refData = await refRes.json()
      const baseCommitSha = refData.object.sha

      // Get base commit tree
      const commitRes = await fetch(
        `https://api.github.com/repos/${owner}/${repository}/git/commits/${baseCommitSha}`,
        { headers: githubHeaders(cleanToken), signal: AbortSignal.timeout(8_000) }
      )
      if (!commitRes.ok) {
        throw new Error(`Failed to fetch base commit details (${commitRes.status})`)
      }
      const commitData = await commitRes.json()
      const baseTreeSha = commitData.tree.sha

      // Create new Git tree with all files
      const treePayload = {
        base_tree: baseTreeSha,
        tree: files.map((f) => ({
          path: f.path,
          mode: '100644',
          type: 'blob',
          content: f.content,
        })),
      }

      const newTreeRes = await fetch(`https://api.github.com/repos/${targetOwner}/${repository}/git/trees`, {
        method: 'POST',
        headers: { ...githubHeaders(cleanToken), 'Content-Type': 'application/json' },
        body: JSON.stringify(treePayload),
        signal: AbortSignal.timeout(8_000),
      })
      if (!newTreeRes.ok) {
        throw new Error(`Failed to build file tree (${newTreeRes.status})`)
      }
      const newTreeData = await newTreeRes.json()
      const newTreeSha = newTreeData.sha

      // Create Git Commit
      const newCommitRes = await fetch(`https://api.github.com/repos/${targetOwner}/${repository}/git/commits`, {
        method: 'POST',
        headers: { ...githubHeaders(cleanToken), 'Content-Type': 'application/json' },
        body: JSON.stringify({
          message: `${prTitle}\n\nAutomated refactor generated by CodeGenome AI.\nValidation: Tests=${validationResult.validation.tests}, Lint=${validationResult.validation.lint}, Build=${validationResult.validation.build}`,
          tree: newTreeSha,
          parents: [baseCommitSha],
        }),
        signal: AbortSignal.timeout(8_000),
      })
      if (!newCommitRes.ok) {
        throw new Error(`Failed to create commit (${newCommitRes.status})`)
      }
      const newCommitData = await newCommitRes.json()
      const newCommitSha = newCommitData.sha

      // Create branch reference
      const createRefRes = await fetch(`https://api.github.com/repos/${targetOwner}/${repository}/git/refs`, {
        method: 'POST',
        headers: { ...githubHeaders(cleanToken), 'Content-Type': 'application/json' },
        body: JSON.stringify({
          ref: `refs/heads/${safeBranch}`,
          sha: newCommitSha,
        }),
        signal: AbortSignal.timeout(8_000),
      })

      if (!createRefRes.ok) {
        // If branch already exists, update reference
        const updateRefRes = await fetch(
          `https://api.github.com/repos/${targetOwner}/${repository}/git/refs/heads/${encodeURIComponent(safeBranch)}`,
          {
            method: 'PATCH',
            headers: { ...githubHeaders(cleanToken), 'Content-Type': 'application/json' },
            body: JSON.stringify({ sha: newCommitSha, force: true }),
            signal: AbortSignal.timeout(8_000),
          }
        )
        if (!updateRefRes.ok) {
          throw new Error(`Failed to create or update branch ref (${createRefRes.status})`)
        }
      }

      // Try creating GitHub Pull Request directly
      const headBranch = isCrossFork ? `${targetOwner}:${safeBranch}` : safeBranch
      const prCreateRes = await fetch(`https://api.github.com/repos/${owner}/${repository}/pulls`, {
        method: 'POST',
        headers: { ...githubHeaders(cleanToken), 'Content-Type': 'application/json' },
        body: JSON.stringify({
          title: prTitle,
          head: headBranch,
          base: targetBaseBranch,
          body: prBody,
          maintainer_can_modify: true,
        }),
        signal: AbortSignal.timeout(10_000),
      })

      if (prCreateRes.ok) {
        const prData = await prCreateRes.json()
        return {
          success: true,
          mode: 'live',
          pushed: true,
          prUrl: prData.html_url,
          branch: safeBranch,
          baseBranch: targetBaseBranch,
          title: prTitle,
          body: prBody,
          cliCommand,
          validation: validationResult.validation,
          message: `Pull Request #${prData.number} successfully created on GitHub!`,
        }
      } else {
        const compareUrl = `https://github.com/${owner}/${repository}/compare/${targetBaseBranch}...${headBranch}?expand=1`
        return {
          success: true,
          mode: 'live',
          pushed: true,
          prUrl: compareUrl,
          branch: safeBranch,
          baseBranch: targetBaseBranch,
          title: prTitle,
          body: prBody,
          cliCommand,
          validation: validationResult.validation,
          message: `Branch '${safeBranch}' successfully created and pushed to GitHub! Click to review and open your Pull Request.`,
        }
      }
    } catch (error) {
      console.warn('[PR Service] Live API attempt fallback:', error.message)
      return {
        success: true,
        mode: 'simulated',
        pushed: false,
        prUrl: null,
        branch: safeBranch,
        baseBranch: targetBaseBranch,
        title: prTitle,
        body: prBody,
        patch,
        cliCommand,
        validation: validationResult.validation,
        message: `Changes prepared and validated for ${owner}/${repository}! To create a live Pull Request on GitHub, sign in or enter a Personal Access Token to fork and push.`,
      }
    }
  }

  // Fallback when live API push token is restricted or unavailable:
  return {
    success: true,
    mode: 'simulated',
    pushed: false,
    prUrl: null,
    branch: safeBranch,
    baseBranch: defaultBranch,
    title: prTitle,
    body: prBody,
    patch,
    cliCommand,
    validation: validationResult.validation,
    message: `Refactor branch '${safeBranch}' prepared and sandbox-verified for ${owner}/${repository}! Enter a GitHub Personal Access Token to fork and push automatically, or use the Git CLI patch below.`,
  }
}
